/**
 * Generates app/motion-curves.css from Remotion's spring physics.
 *
 * Remotion is a video framework: it renders React frame by frame. That makes it
 * the wrong tool for animating a live page, but its spring solver is exactly
 * the right tool for *designing* the easing a live page uses. This script
 * samples `spring()` at 60fps for each of the site's motion characters and
 * writes the samples out as CSS `linear()` easing functions, so the browser
 * animates with real spring physics through plain CSS transitions — no
 * animation runtime in the client bundle, no per-frame JS.
 *
 * Remotion is therefore a devDependency only; nothing here ships to visitors
 * but the generated numbers.
 *
 * Regenerate after changing a spring config:
 *   npm run motion:curves
 */
import { spring, measureSpring, Easing } from "remotion";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const FPS = 60;
/** Samples per curve. `linear()` spaces its stops evenly, so this is the only
 * knob controlling how faithfully the curve follows the real spring. */
const SAMPLES = 40;

/**
 * The site's motion characters. `damping` dominates the feel: 200 is a pure
 * push with no overshoot, the lower values overshoot and settle.
 */
const SPRINGS = {
  // Everyday reveals — arrives, does not bounce.
  "spring-soft": { damping: 200, stiffness: 100, mass: 1 },
  // A little overshoot, for anything that should feel like it snaps into place.
  "spring-snap": { damping: 26, stiffness: 120, mass: 1 },
  // Openly springy — the "kinetic" motion style.
  "spring-bounce": { damping: 12, stiffness: 140, mass: 1 },
};

/** Fixed-duration bezier characters, kept here so every easing token in the
 * stylesheet has one source. These need no sampling — CSS has cubic-bezier —
 * but the generator owns them so the file stays the single place to look. */
const BEZIERS = {
  "ease-out-expo": [0.16, 1, 0.3, 1],
  "ease-in-out-soft": [0.65, 0, 0.35, 1],
};

/** A `linear()` easing string tracing `config`'s spring, plus its settle time. */
function springCurve(config) {
  const frames = measureSpring({ fps: FPS, config, threshold: 0.001 });
  const stops = [];
  for (let i = 0; i < SAMPLES; i++) {
    const frame = (i / (SAMPLES - 1)) * frames;
    stops.push(spring({ frame, fps: FPS, config, durationInFrames: frames }));
  }
  // Pin the ends: sampling can land a hair off 0/1 and a curve that does not
  // start and finish exactly where the animation does reads as a flicker.
  stops[0] = 0;
  stops[stops.length - 1] = 1;
  return {
    curve: `linear(${stops.map((v) => Number(v.toFixed(4))).join(", ")})`,
    ms: Math.round((frames / FPS) * 1000),
  };
}

/** The closest cubic-bezier to each spring, for browsers without `linear()`. */
const FALLBACK = {
  "spring-soft": "cubic-bezier(0.22, 1, 0.36, 1)",
  "spring-snap": "cubic-bezier(0.34, 1.56, 0.64, 1)",
  "spring-bounce": "cubic-bezier(0.34, 1.8, 0.64, 1)",
};

const lines = [
  "/* GENERATED by scripts/generate-motion-curves.mjs — do not edit by hand.",
  " *",
  " * Spring curves sampled from Remotion's spring solver (see the script) and",
  " * written as CSS `linear()` easings, so transitions here follow real spring",
  " * physics with no animation library in the bundle. Each spring also exports",
  " * the duration it actually takes to settle, so a transition can be timed to",
  " * its own curve instead of a guessed round number.",
  " *",
  " * Regenerate with `npm run motion:curves`.",
  " */",
  "",
  ":root {",
];

for (const [name, config] of Object.entries(SPRINGS)) {
  const { ms } = springCurve(config);
  lines.push(`  --${name}: ${FALLBACK[name]};`);
  lines.push(`  --${name}-ms: ${ms}ms;`);
}
for (const [name, b] of Object.entries(BEZIERS)) {
  lines.push(`  --${name}: cubic-bezier(${b.join(", ")});`);
}
lines.push("}", "");
lines.push("/* Real spring shapes, where the browser can draw them. */");
lines.push("@supports (animation-timing-function: linear(0, 1)) {");
lines.push("  :root {");
for (const [name, config] of Object.entries(SPRINGS)) {
  lines.push(`    --${name}: ${springCurve(config).curve};`);
}
lines.push("  }", "}", "");

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "app", "motion-curves.css");
writeFileSync(out, lines.join("\n"));

console.log(`wrote ${out}`);
for (const [name, config] of Object.entries(SPRINGS)) {
  console.log(`  --${name}: settles in ${springCurve(config).ms}ms`);
}
console.log(`  ${Object.keys(BEZIERS).length} bezier tokens`);
console.log(`  Easing.bezier sanity: ${Easing.bezier(...BEZIERS["ease-out-expo"])(0.5).toFixed(3)}`);
